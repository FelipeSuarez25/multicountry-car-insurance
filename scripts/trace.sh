#!/usr/bin/env bash
# Deterministic traceability matrix for one user story (no AI involved).
#
#   scripts/trace.sh US-01            print the matrix; exit 1 if the story is not traceable
#   scripts/trace.sh US-01 --no-fail  print only, always exit 0
#
# For every acceptance criterion (US-XX-AC-NN) and business rule (US-XX-BR-NN) in
# specs/US-XX/spec.md, it finds:
#   - tests whose files mention the ID (*.spec.ts / *.test.ts outside node_modules)
#   - commits on the current branch whose message mentions the ID
#   - review reports that mention the ID
# It also lists review findings (US-XX-RN-FNN) that are still open.
#
# Exit 1 when: an AC has no test and is not marked "manual" in the spec's test mapping,
# or a blocker/major finding is still open.
# Compatible with macOS bash 3.2 (no associative arrays, no mapfile).

set -euo pipefail

usage() { echo "usage: $0 US-NN [--no-fail]" >&2; exit 2; }
[ $# -ge 1 ] || usage
US="$1"
NO_FAIL="${2:-}"
[[ "$US" =~ ^US-[0-9]{2}$ ]] || usage

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"
SPEC="specs/$US/spec.md"
[ -f "$SPEC" ] || { echo "error: $SPEC not found" >&2; exit 2; }

# IDs defined in the spec, excluding retired ones (~~US-XX-AC-NN~~).
ids_of() {
  grep -oE "$US-$1-[0-9]{2}" "$SPEC" | sort -u | while read -r id; do
    grep -q "~~$id~~" "$SPEC" || echo "$id"
  done
}

test_files() {
  local dirs=()
  for d in frontend backend; do [ -d "$d" ] && dirs+=("$d"); done
  [ ${#dirs[@]} -gt 0 ] || return 0
  grep -rlE --include='*.spec.ts' --include='*.test.ts' --exclude-dir=node_modules \
    --exclude-dir=dist --exclude-dir=.angular "$1([^0-9]|$)" "${dirs[@]}" 2>/dev/null | sort || true
}

commits_of() {
  git log --format='%h' --extended-regexp --grep="$1([^0-9]|$)" 2>/dev/null | head -5 | paste -sd ' ' - || true
}

reviews_of() {
  [ -d reviews ] || return 0
  grep -lE "$1([^0-9]|$)" reviews/"$US"-review-R*.md 2>/dev/null | xargs -n1 basename 2>/dev/null | paste -sd ' ' - || true
}

is_manual() {
  # A row in the test-mapping table: | US-XX-AC-NN | manual ... |
  grep -qiE "^\|[[:space:]]*$1[[:space:]]*\|[^|]*manual" "$SPEC"
}

join_lines() { paste -sd ',' - | sed 's/,/, /g'; }

missing=0
echo "# Traceability matrix — $US"
echo
echo "Generated by \`scripts/trace.sh\` on $(date +%Y-%m-%d) at commit \`$(git rev-parse --short HEAD)\` (branch \`$(git branch --show-current)\`)."
echo
echo "Related ADRs (from spec): $(grep -oE 'ADR-[0-9]{4}' "$SPEC" | sort -u | join_lines || true)"
echo

for kind in AC BR; do
  ids="$(ids_of "$kind")"
  [ -n "$ids" ] || continue
  [ "$kind" = AC ] && echo "## Acceptance criteria" || echo "## Business rules"
  echo
  echo "| ID | Tests | Commits | Reviews | Status |"
  echo "|---|---|---|---|---|"
  for id in $ids; do
    tests="$(test_files "$id" | join_lines)"
    commits="$(commits_of "$id")"
    reviews="$(reviews_of "$id")"
    if [ -n "$tests" ]; then
      status="✅ tested"
    elif is_manual "$id"; then
      status="🖐 manual (per spec)"
    elif [ "$kind" = AC ]; then
      status="❌ no test"; missing=$((missing + 1))
    else
      status="⚠️ no direct test (check covering AC)"
    fi
    echo "| $id | ${tests:-—} | ${commits:-—} | ${reviews:-—} | $status |"
  done
  echo
done

open_blocking=0
if ls reviews/"$US"-review-R*.md >/dev/null 2>&1; then
  echo "## Open review findings"
  echo
  # Latest status per finding: later rounds override earlier ones (files sorted by round).
  rows="$(grep -hE "^\|[[:space:]]*$US-R[0-9]+-F[0-9]+[[:space:]]*\|" $(ls reviews/"$US"-review-R*.md | sort -V) || true)"
  open_rows="$(echo "$rows" | awk -F'|' 'NF>2 { id=$2; gsub(/ /,"",id); last[id]=$0 } END { for (k in last) print last[k] }' \
    | grep -iE '\|[[:space:]]*open[[:space:]]*\|' || true)"
  if [ -n "$open_rows" ]; then
    echo "$open_rows"
    open_blocking=$(echo "$open_rows" | grep -ciE '\|[[:space:]]*(blocker|major)[[:space:]]*\|' || true)
  else
    echo "None."
  fi
  echo
fi

echo "**Summary:** ACs without test: $missing · open blocker/major findings: $open_blocking"

if [ "$NO_FAIL" != "--no-fail" ] && { [ "$missing" -gt 0 ] || [ "$open_blocking" -gt 0 ]; }; then
  exit 1
fi
